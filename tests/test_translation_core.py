class TestPureHelpers:
    def test_parse_command_with_pair(self, core):
        assert core.parse_command("/translate en fa hello world") == ("hello world", "en", "fa")

    def test_parse_command_arrow_pair(self, core):
        assert core.parse_command("/translate de->ru gut tag") == ("gut tag", "de", "ru")

    def test_parse_command_body_only(self, core):
        # Two short leading tokens are always read as a language pair
        # ("some"/"words" would be); a non-code word defeats the pair
        # regex and everything after /translate is the body.
        assert core.parse_command("/translate hello_world some text") == ("hello_world some text", None, None)

    def test_parse_command_passthrough(self, core):
        assert core.parse_command("just text") == ("just text", None, None)

    def test_is_referential(self, core):
        assert core.is_referential("translate this")
        assert core.is_referential("ترجمه")
        assert core.is_referential("")
        assert not core.is_referential("translate this whole document about quantum mechanics")

    def test_context_blocks_strips_source_tags(self, core):
        # One block per <context> occurrence (v0.11.3 injects one), inner
        # <source> tags stripped, multiple sources merged.
        text = 'before <context>\n<source id="1" name="a.md">BODY ONE</source>\n<source id="2" name="b.md">BODY TWO</source>\n</context> after'
        assert core.context_blocks(text) == ["BODY ONE\nBODY TWO"]

    def test_current_remainder_strips_instruction_line(self, core):
        t = "Please translate this:\n\nThe actual content that should survive."
        assert core.current_remainder(t, "") == "The actual content that should survive."

    def test_current_remainder_keeps_real_sentences(self, core):
        t = "The moon lands softly on dark soil tonight."
        assert core.current_remainder(t, "") == t

    def test_current_remainder_first_line_instruction_dropped(self, core):
        # Pinned limitation: a single line that merely *starts* with an
        # instruction word is dropped even when it is a full sentence.
        assert core.current_remainder("Translate the moon lands softly.", "") == ""

    def test_strip_wrappers(self, core):
        t = '<attached_files>\n<file id="1"/>\n</attached_files>\nreal text'
        assert core.strip_wrappers(t) == "real text"


class TestSanitize:
    def test_base64_stripped_alt_kept(self, core):
        t = "Intro text\n![diagram](data:image/png;base64,iVBORw0KGgoAAAANS)\nOutro"
        out = core.sanitize_document(t)
        assert "iVBORw0KGgo" not in out
        assert "diagram" in out
        assert "Intro text" in out and "Outro" in out

    def test_html_tags_stripped_inner_kept(self, core):
        out = core.sanitize_document("A <b>bold</b> word <!-- comment --> end")
        assert out == "A bold word end"

    def test_image_only_empty(self, core):
        # Alt text is translatable and deliberately kept; an image with no
        # alt is the true "nothing left" case.
        assert core.sanitize_document("![](data:image/png;base64,AAAA)") == ""


class TestResolveFromMessages:
    def test_system_prompt_never_a_source(self, core):
        messages = [
            {"role": "system", "content": "You are a helpful assistant with secrets."},
            {"role": "user", "content": "translate this"},
        ]
        text, source = core.resolve_from_messages(
            "translate this", messages, 1, "translate this", ""
        )
        assert text == ""
        assert source == ""

    def test_earlier_context_block_wins_over_history(self, core):
        messages = [
            {"role": "user", "content": "here you go"},
            {"role": "user", "content": "<context>\n<source id='1' name='doc.md'>EARLIER DOC</source>\n</context>\ntranslate it"},
            {"role": "assistant", "content": "ok"},
            {"role": "user", "content": "translate this"},
        ]
        text, source = core.resolve_from_messages(
            "translate this", messages, 3, "translate this", ""
        )
        assert text == "EARLIER DOC"
        assert source == "earlier document"

    def test_assistant_history_excluded_when_flagged(self, core):
        # Pipe mode: a previous pipe reply (plain assistant text, no tool
        # calls) must not be picked as the source of "translate this".
        messages = [
            {"role": "user", "content": "The quick brown fox jumps over the lazy dog."},
            {"role": "assistant", "content": "سگ تنبل"},  # previous translation
            {"role": "user", "content": "translate this"},
        ]
        text, source = core.resolve_from_messages(
            "translate this", messages, 2, "translate this", "",
            include_assistant_history=False,
        )
        assert text == "The quick brown fox jumps over the lazy dog."
        assert source == "conversation history"

    def test_tool_mode_relay_indices_skip_relay(self, core):
        messages = [
            {"role": "user", "content": "translate the document"},
            {
                "role": "assistant",
                "content": None,
                "tool_calls": [{"id": "c1", "function": {"name": "translate", "arguments": "{}"}}],
            },
            {"role": "tool", "tool_call_id": "c1", "content": "FULL TRANSLATION BODY"},
            {"role": "assistant", "content": "FULL TRANSLATION BODY"},
            {"role": "user", "content": "translate this"},
        ]
        # tool mode (include assistant history): the relay assistant message
        # is skipped, so no source is found here (the real doc is elsewhere).
        text, _ = core.resolve_from_messages(
            "translate this", messages, 5, "translate this", ""
        )
        assert text == ""
        # but the user's original instruction message has no body either.
        relays = core.translation_relay_indices(messages)
        assert 3 in relays


class TestResolveLanguages:
    def test_explicit_beats_valves(self, core):
        assert core.resolve_languages("en", "fa", {"valves": {"source_lang": "de", "target_lang": "ru"}}, "x", "y") == ("en", "fa")

    def test_dict_valves(self, core):
        assert core.resolve_languages(None, None, {"valves": {"source_lang": "de", "target_lang": "ru"}}, "en", "fa") == ("de", "ru")

    def test_instance_valves_pydantic_v2_shape(self, core):
        # Production shape: OpenWebUI injects a UserValves *instance*
        # (pydantic v2 models are not mappings — `**instance` would fail).
        class Valves:
            source_lang = "de"
            target_lang = "ru"

        assert core.resolve_languages(None, None, {"valves": Valves()}, "en", "fa") == ("de", "ru")

    def test_defaults(self, core):
        assert core.resolve_languages(None, None, {}, "en", "fa") == ("en", "fa")
        assert core.resolve_languages(None, None, None, "en", "fa") == ("en", "fa")


