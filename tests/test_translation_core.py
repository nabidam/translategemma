class TestResolveSource:
    @staticmethod
    def _run(coro):
        loop = asyncio.new_event_loop()
        try:
            return loop.run_until_complete(coro)
        finally:
            loop.close()

    def test_explicit_text_wins(self, core):
        info = self._run(core.resolve_source("A real document body here to translate.", [], []))
        assert info["text"] == "A real document body here to translate."
        assert info["source"] == "provided text"

    def test_referential_goes_to_messages(self, core):
        messages = [
            {"role": "user", "content": [{"type": "text", "text": "<context>\n<source id='1' name='d.md'>DOC BODY</source>\n</context>\ntranslate this"}]},
        ]
        info = self._run(core.resolve_source("translate this", messages, []))
        assert info["text"] == "DOC BODY"
        assert info["source"] == "document context"

    def test_command_languages_extracted(self, core):
        info = self._run(core.resolve_source("/translate en de some words to translate", [], []))
        assert info["cmd_src"] == "en"
        assert info["cmd_tgt"] == "de"
        assert info["text"] == "some words to translate"

    def test_pasted_text_message(self, core):
        # Pipe shape: no argument, the user message IS the content.
        messages = [
            {"role": "user", "content": [{"type": "text", "text": "The quick brown fox jumps over the lazy dog."}]},
        ]
        info = self._run(core.resolve_source("", messages, []))
        assert info["text"] == "The quick brown fox jumps over the lazy dog."
        assert info["source"] == "message text"
