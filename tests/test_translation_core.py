class _Resp:
    def __init__(self, status_code, payload=None, text=""):
        self.status_code = status_code
        self._payload = payload or {}
        self.text = text

    def json(self):
        return self._payload


class TestTranslationClient:
    def test_gateway_success(self, core, monkeypatch):
        calls = []

        def fake_post(url, json=None, timeout=None):
            calls.append((url, json, timeout))
            return _Resp(200, {"translation": "TARJOMEH"})

        core.requests.post = fake_post
        client = core.TranslationClient(
            backend_mode="gateway",
            gateway_url="http://gw/translate",
            max_new_tokens=512,
            timeout_seconds=60,
        )
        out = client.translate("hello", "en", "fa", True)
        assert out == "TARJOMEH"
        url, payload, timeout = calls[0]
        assert url == "http://gw/translate"
        assert payload == {
            "text": "hello",
            "source_lang": "en",
            "target_lang": "fa",
            "max_new_tokens": 512,
            "split_sentences": True,
        }
        assert timeout == 60

    def test_gateway_error_string(self, core, monkeypatch):
        def fake_post(url, json=None, timeout=None):
            return _Resp(502, text="upstream is down")

        core.requests.post = fake_post
        client = core.TranslationClient(backend_mode="gateway")
        out = client.translate("hello", "en", "fa", True)
        assert out.startswith("Gateway Error (502):")

    def test_vllm_mode_payload(self, core, monkeypatch):
        calls = []

        def fake_post(url, json=None, timeout=None):
            calls.append((url, json))
            return _Resp(200, {"choices": [{"message": {"content": "FA"}}]})

        core.requests.post = fake_post
        client = core.TranslationClient(
            backend_mode="vllm",
            vllm_url="http://vllm/v1/chat/completions",
            vllm_model_name="mt",
            max_new_tokens=256,
        )
        out = client.translate("hello", "en", "fa", False)
        assert out == "FA"
        url, payload = calls[0]
        assert url == "http://vllm/v1/chat/completions"
        assert payload["model"] == "mt"
        assert payload["stop_token_ids"] == [1, 106]
        assert payload["temperature"] == 0.0
        assert payload["messages"][0]["content"][0]["text"] == "hello"

    def test_vllm_error_string(self, core, monkeypatch):
        def fake_post(url, json=None, timeout=None):
            return _Resp(400, text="prompt too long")

        core.requests.post = fake_post
        client = core.TranslationClient(backend_mode="vllm")
        out = client.translate("hello", "en", "fa", False)
        assert out.startswith("vLLM Error (400):")


